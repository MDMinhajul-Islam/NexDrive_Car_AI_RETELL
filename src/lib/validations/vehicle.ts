import { z } from "zod";
import {
  BODY_TYPES,
  DRIVETRAINS,
  FUEL_TYPES,
  TRANSMISSIONS,
  VEHICLE_CONDITIONS,
  VEHICLE_STATUSES,
  VEHICLE_YEAR_MAX,
  VEHICLE_YEAR_MIN,
} from "@/lib/constants";

const text = (label: string, max = 80) =>
  z.string().trim().min(1, `${label} is required`).max(max, `${label} is too long`);

const whole = (label: string, min: number, max: number) =>
  z
    .number({ message: `${label} must be a number` })
    .int(`${label} must be a whole number`)
    .min(min, `${label} must be at least ${min.toLocaleString("en-US")}`)
    .max(max, `${label} must be at most ${max.toLocaleString("en-US")}`);

const money = (label: string) =>
  z
    .number({ message: `${label} must be a number` })
    .positive(`${label} must be greater than 0`)
    .max(10_000_000, `${label} is too large`);

/**
 * Mirrors the check constraints on public.vehicles:
 *  - vin: 17 characters, letters and digits except I, O, Q
 *  - year 1980 to 2035, mileage 0 to 500,000, seating 1 to 15
 *  - body_type, condition, fuel_type, transmission, drivetrain, vehicle_status from fixed lists
 *  - msrp > 0, and 0 < sale_price <= msrp
 *  - test_drive_available only when status is Available or Demo Vehicle
 *  - a New vehicle has at most 500 miles
 *  - a Certified Pre-Owned vehicle needs a certification other than "None"
 * vehicle_id and stock_number are generated by the database.
 */
export const vehicleSchema = z
  .object({
    vin: z
      .string()
      .trim()
      .toUpperCase()
      .regex(/^[A-HJ-NPR-Z0-9]{17}$/, "VIN must be 17 characters: letters and digits, without I, O or Q"),
    year: whole("Year", VEHICLE_YEAR_MIN, VEHICLE_YEAR_MAX),
    make: text("Make", 40),
    model: text("Model", 60),
    trim: text("Trim", 60),
    body_type: z.enum(BODY_TYPES, { message: "Choose a body type" }),
    condition: z.enum(VEHICLE_CONDITIONS, { message: "Choose a condition" }),
    fuel_type: z.enum(FUEL_TYPES, { message: "Choose a fuel type" }),
    transmission: z.enum(TRANSMISSIONS, { message: "Choose a transmission" }),
    drivetrain: z.enum(DRIVETRAINS, { message: "Choose a drivetrain" }),
    vehicle_status: z.enum(VEHICLE_STATUSES, { message: "Choose a status" }),
    mileage: whole("Mileage", 0, 500_000),
    seating_capacity: whole("Seating", 1, 15),
    msrp: money("MSRP"),
    sale_price: money("Sale price"),
    exterior_color: text("Exterior color", 60),
    interior_color: text("Interior color", 60),
    warranty: text("Warranty", 120),
    certification: text("Certification", 120),
    dealership_location: text("Location", 80),
    test_drive_available: z.boolean(),
    is_featured: z.boolean(),
    feature_ids: z.array(z.string().regex(/^FEAT-[0-9]{3}$/)).max(200),
  })
  .superRefine((v, ctx) => {
    if (v.sale_price > v.msrp) {
      ctx.addIssue({ code: "custom", path: ["sale_price"], message: "Sale price cannot be higher than MSRP" });
    }
    if (v.test_drive_available && v.vehicle_status !== "Available" && v.vehicle_status !== "Demo Vehicle") {
      ctx.addIssue({
        code: "custom",
        path: ["test_drive_available"],
        message: "Test drives are only allowed when the status is Available or Demo Vehicle",
      });
    }
    if (v.condition === "New" && v.mileage > 500) {
      ctx.addIssue({ code: "custom", path: ["mileage"], message: "A New vehicle can have at most 500 miles" });
    }
    if (v.condition === "Certified Pre-Owned" && v.certification.trim().toLowerCase() === "none") {
      ctx.addIssue({
        code: "custom",
        path: ["certification"],
        message: "A Certified Pre-Owned vehicle needs a certification other than None",
      });
    }
  });

export type VehicleInput = z.infer<typeof vehicleSchema>;

/** vehicle_images.storage_path check: vehicles/<vehicle_id>/<file>.(webp|jpg|jpeg|png|avif) */
export const IMAGE_EXTENSIONS = ["webp", "jpg", "jpeg", "png", "avif"] as const;
export const IMAGE_MIME_TYPES = ["image/webp", "image/jpeg", "image/png", "image/avif"] as const;
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

export function storagePathPattern(vehicleId: string) {
  return new RegExp(`^vehicles/${vehicleId}/[A-Za-z0-9][A-Za-z0-9._/-]*\\.(webp|jpg|jpeg|png|avif)$`);
}
